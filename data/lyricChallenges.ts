export function getShuffledLyricChallenges(
  count: number = 5,
  excludeIds: string[] = []
): LyricChallengeItem[] {
  const excluded = new Set(excludeIds);
  const pool = LYRIC_CHALLENGES.filter((c) => !excluded.has(c.id));
  const source = pool.length >= count ? pool : LYRIC_CHALLENGES;

  // Shuffle copy and pick at most 1 snippet per song in a single round
  const shuffled = [...source];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const picked: LyricChallengeItem[] = [];
  const usedSongs = new Set<string>();
  for (const item of shuffled) {
    if (usedSongs.has(item.songId)) continue;
    picked.push(item);
    usedSongs.add(item.songId);
    if (picked.length >= count) break;
  }

  return picked;
}
